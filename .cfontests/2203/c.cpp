int fx(int s, int m){
  if(s==0)return 0;
  int nm = m;
  int ns = s%m;
  while(nm>ns){
    nm &= ~(1ll<<(63 - __builtin_clzll(nm)));
  }
  // dbg(ns,nm,s/m);
  return s/m+fx(ns,nm);
}
